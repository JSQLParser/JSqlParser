class ColumnIdentityActionTest {
    @ParameterizedTest
    @ValueSource(strings = {"ADD GENERATED ALWAYS AS IDENTITY (CACHE 10)",
            "SET GENERATED BY DEFAULT", "SET CACHE 10", "RESTART WITH 20",
            "DROP IDENTITY IF EXISTS"})
    void exposesOriginalColumnAndKeepsEachActionKind(String clause) throws JSQLParserException {
        Alter statement = parse("ALTER TABLE t ALTER COLUMN id " + clause);
        AlterExpression action = first(statement);
        ColumnIdentityAction column = action.getColumnIdentityActions().get(0);
        assertSame(action.getColDataTypeList().get(0), column);
        assertSame(action.getColDataTypeList().get(0).getIdentityAlterations(),
                column.getIdentityAlterations());
        assertNull(action.getColDataTypeList().get(0).getColDataType());
        column.setColumnName("\"New Id\"");
        assertEquals("ALTER TABLE t ALTER COLUMN \"New Id\" " + clause, statement.toString());
        roundTrip(statement);
    }

    @Test
    void addModeAndParametersEditTheDefinitionAndFollowReplacements() throws JSQLParserException {
        Alter statement = parse("ALTER TABLE t ALTER COLUMN id "
                + "ADD GENERATED BY DEFAULT AS IDENTITY (CACHE 10)");
        IdentityAlteration action = identity(statement);
        IdentityDefinition original = action.getIdentityDefinition();
        assertEquals(GenerationMode.BY_DEFAULT, action.getGenerationMode());
        assertSame(original.getParameters(), action.getParameters());
        action.setGenerationMode(GenerationMode.ALWAYS);
        action.getParameters().get(0).setValue(20L);
        assertEquals(GenerationMode.ALWAYS, original.getGenerationMode());
        assertEquals("ALTER TABLE t ALTER COLUMN id "
                + "ADD GENERATED ALWAYS AS IDENTITY (CACHE 20)", statement.toString());
        roundTrip(statement);

        IdentityDefinition replacement = new IdentityDefinition(GenerationMode.BY_DEFAULT);
        action.setIdentityDefinition(replacement);
        assertEquals(GenerationMode.BY_DEFAULT, action.getGenerationMode());
        assertNull(action.getParameters());
        action.setParameters(List.of(cache(30)));
        assertSame(replacement.getParameters(), action.getParameters());
        replacement.setGenerationMode(GenerationMode.ALWAYS);
        assertEquals(GenerationMode.ALWAYS, action.getGenerationMode());
        assertEquals("ALTER TABLE t ALTER COLUMN id "
                + "ADD GENERATED ALWAYS AS IDENTITY (CACHE 30)", statement.toString());
        roundTrip(statement);

        action.setIdentityDefinition(null);
        assertNull(action.getGenerationMode());
        assertNull(action.getParameters());
        action.setGenerationMode(GenerationMode.BY_DEFAULT);
        assertNotSame(original, action.getIdentityDefinition());
        assertNotSame(replacement, action.getIdentityDefinition());
        assertNull(action.getParameters());
        roundTrip(statement);
    }

    @Test
    void addBuilderCreatesOnlyTheRequestedDefinition() {
        IdentityAlteration action = new IdentityAlteration(IdentityAlteration.Kind.ADD);
        assertNull(action.getGenerationMode());
        assertNull(action.getParameters());
        action.setGenerationMode(null);
        action.setParameters(null);
        assertNull(action.getIdentityDefinition());
        action.setParameters(List.of(cache(10)));
        assertEquals(GenerationMode.BY_DEFAULT, action.getGenerationMode());
        assertEquals("ADD GENERATED BY DEFAULT AS IDENTITY (CACHE 10)", action.toString());
        IdentityDefinition definition = action.getIdentityDefinition();
        action.setGenerationMode(GenerationMode.ALWAYS);
        action.setParameters(null);
        assertSame(definition, action.getIdentityDefinition());
        assertEquals("ADD GENERATED ALWAYS AS IDENTITY", action.toString());
        action.setGenerationMode(null);
        assertNull(definition.getGenerationMode());
    }

    @Test
    void orderedSetAndRestartActionsRemainIndependentAndEditable() throws JSQLParserException {
        Alter statement = parse("ALTER TABLE t ALTER COLUMN id "
                + "SET GENERATED BY DEFAULT SET CACHE 10 RESTART 20");
        ColumnIdentityAction column = first(statement).getColumnIdentityActions().get(0);
        List<IdentityAlteration> actions = column.getIdentityAlterations();
        assertEquals(List.of(IdentityAlteration.Kind.SET_GENERATED,
                IdentityAlteration.Kind.SET_PARAMETER, IdentityAlteration.Kind.RESTART),
                actions.stream().map(IdentityAlteration::getKind).collect(Collectors.toList()));
        actions.get(0).setGenerationMode(GenerationMode.ALWAYS);
        actions.get(1).getParameters().get(0).setValue(30L);
        actions.get(2).setRestartWith(null);
        assertEquals("ALTER TABLE t ALTER COLUMN id SET GENERATED ALWAYS SET CACHE 30 RESTART",
                statement.toString());
        roundTrip(statement);

        IdentityAlteration drop = new IdentityAlteration(IdentityAlteration.Kind.DROP);
        drop.setIfExists(true);
        column.setIdentityAlterations(List.of(drop));
        assertSame(drop, identity(statement));
        assertNotSame(actions, column.getIdentityAlterations());
        assertEquals("ALTER TABLE t ALTER COLUMN id DROP IDENTITY IF EXISTS", statement.toString());
        roundTrip(statement);
        drop.setIfExists(false);
        assertEquals("ALTER TABLE t ALTER COLUMN id DROP IDENTITY", statement.toString());
        roundTrip(statement);
    }

    @Test
    void unrelatedIdentityPropertiesDoNotChangeRestartOrDropRendering() {
        for (IdentityAlteration.Kind kind : List.of(IdentityAlteration.Kind.RESTART,
                IdentityAlteration.Kind.DROP)) {
            IdentityAlteration action = new IdentityAlteration(kind);
            String before = action.toString();
            action.setIdentityDefinition(new IdentityDefinition(GenerationMode.ALWAYS));
            action.setGenerationMode(GenerationMode.ALWAYS);
            action.setParameters(List.of(cache(50)));
            assertEquals(before, action.toString());
        }
    }

    @Test
    void lookupKeepsColumnMembershipSeparateFromMutableActions() throws JSQLParserException {
        Alter statement = parse("ALTER TABLE t ALTER COLUMN id RESTART WITH 20, "
                + "ALTER COLUMN other TYPE bigint");
        AlterExpression action = first(statement);
        List<ColumnIdentityAction> columns = action.getColumnIdentityActions();
        assertEquals(1, columns.size());
        assertTrue(statement.getAlterExpressions().get(1).getColumnIdentityActions().isEmpty());
        assertThrows(UnsupportedOperationException.class, columns::clear);
        ColumnIdentityAction column = columns.get(0);
        ColumnDataType stored = action.getColDataTypeList().get(0);
        stored.setColDataType(new ColDataType("bigint"));
        stored.setIdentityAlterations(null);
        assertNull(column.getIdentityAlterations());
        assertTrue(action.getColumnIdentityActions().isEmpty());
        assertEquals(1, columns.size());
        column.setIdentityAlterations(
                List.of(new IdentityAlteration(IdentityAlteration.Kind.RESTART)));
        assertSame(column, action.getColumnIdentityActions().get(0));
        action.setOperation(AlterOperation.DROP);
        assertTrue(action.getColumnIdentityActions().isEmpty());
        action.setOperation(AlterOperation.ALTER);
        assertSame(column, action.getColumnIdentityActions().get(0));
        roundTrip(statement);
        column.getIdentityAlterations().clear();
        assertTrue(action.getColumnIdentityActions().isEmpty());
    }

    @ParameterizedTest
    @ValueSource(strings = {"ALTER TABLE t ADD COLUMN id bigint GENERATED ALWAYS AS IDENTITY",
            "ALTER TABLE t ALTER COLUMN id TYPE bigint",
            "ALTER TABLE t ALTER COLUMN id SET DEFAULT 1",
            "ALTER TABLE t DROP COLUMN id"})
    void excludesDeclarationsAndUnrelatedColumnChanges(String sql) throws JSQLParserException {
        Alter statement = parse(sql);
        assertTrue(first(statement).getColumnIdentityActions().isEmpty());
        roundTrip(statement);
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("inactiveColumnBodies")
    void excludesInheritedIdentityPayloadWhenAnotherBodyWins(String description,
            Consumer<AlterExpression> change) throws JSQLParserException {
        AlterExpression action = first(parse("ALTER TABLE t ALTER COLUMN id RESTART"));
        change.accept(action);
        assertTrue(action.getColumnIdentityActions().isEmpty(), description);
    }

    static Stream<Arguments> inactiveColumnBodies() {
        return Stream.of(
                inactive("different operation", action -> action.setOperation(AlterOperation.DROP)),
                inactive("named column", action -> action.setColumnName("other")),
                inactive("comment", action -> action.setCommentText("'text'")),
                inactive("constraint header", action -> {
                    action.setConstraintType("CONSTRAINT");
                    action.setConstraintSymbol("c");
                }),
                inactive("index rename", action -> action.setOldIndex(new Index().withName("old"))),
                inactive("drop default", action -> action.addColDropDefault(
                        new AlterExpression.ColumnDropDefault("other"))),
                inactive("set default", action -> action.addColSetDefault(
                        new AlterExpression.ColumnSetDefault("other", "1"))),
                inactive("visibility", action -> action.addColSetVisibility(
                        new AlterExpression.ColumnSetVisibility("other", true))));
    }

    private static Arguments inactive(String description, Consumer<AlterExpression> change) {
        return Arguments.of(description, change);
    }

    @Test
    void changedDropOperationUsesItsGeneralRendererPrecedence() {
        AlterExpressionDrop action = new AlterExpressionDrop();
        action.setOperation(AlterOperation.ALTER);
        ColumnDataType column = new ColumnDataType(false).withColumnName("id");
        column.setIdentityAlterations(
                List.of(new IdentityAlteration(IdentityAlteration.Kind.RESTART)));
        action.addColDataType(column);
        assertEquals(List.of(column), action.getColumnIdentityActions());
        action.addColSetDefault(new AlterExpression.ColumnSetDefault("other", "1"));
        action.setConstraintType("CONSTRAINT");
        action.setConstraintSymbol("c");
        action.setOldIndex(new Index().withName("old"));
        assertEquals("ALTER id RESTART", action.toString());
        assertEquals(List.of(column), action.getColumnIdentityActions());
        column.setColumnName("renamed");
        assertEquals("ALTER renamed RESTART", action.toString());
        action.setColumnName("other");
        assertTrue(action.getColumnIdentityActions().isEmpty());
        assertEquals("ALTER other", action.toString());
        action.setColumnName(null);
        action.setOperation(AlterOperation.DROP);
        assertTrue(action.getColumnIdentityActions().isEmpty());
    }

    @ParameterizedTest
    @MethodSource("fixedBodies")
    void fixedActionRenderersDoNotExposeInactiveColumnIdentityData(AlterExpression action) {
        action.setOperation(AlterOperation.ALTER);
        ColumnDataType column = new ColumnDataType(false).withColumnName("id");
        column.setIdentityAlterations(
                List.of(new IdentityAlteration(IdentityAlteration.Kind.RESTART)));
        action.addColDataType(column);
        assertTrue(action.getColumnIdentityActions().isEmpty());
    }

    static Stream<AlterExpression> fixedBodies() {
        return Stream.of(new AlterConstraintAttributes(), new AlterExpressionCharset(),
                new AlterExpressionOrderBy(), new AlterExpressionPartition(),
                new AlterExpressionPrimaryKey(), new AlterExpressionRename(),
                new AlterExpressionTableOption(), new AlterForeignDataOptions(),
                new RelationAlterAction());
    }

    private static Sequence.Parameter cache(long value) {
        return new Sequence.Parameter(Sequence.ParameterType.CACHE).withValue(value);
    }

    private static Alter parse(String sql) throws JSQLParserException {
        return (Alter) CCJSqlParserUtil.parse(sql,
                parser -> parser.withDialect(Dialect.POSTGRESQL));
    }

    private static AlterExpression first(Alter statement) {
        return statement.getAlterExpressions().get(0);
    }

    private static IdentityAlteration identity(Alter statement) {
        return first(statement).getColumnIdentityActions().get(0).getIdentityAlterations().get(0);
    }

    private static void roundTrip(Alter statement) throws JSQLParserException {
        StringBuilder sql = new StringBuilder();
        statement.accept(new StatementDeParser(sql), null);
        assertEquals(statement.toString(), sql.toString());
        assertEquals(sql.toString(), parse(sql.toString()).toString());
    }
}
