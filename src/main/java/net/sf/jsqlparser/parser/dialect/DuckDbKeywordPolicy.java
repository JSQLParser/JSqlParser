    private DuckDbKeywordPolicy() {}

    /** DuckDB's keywords and their categories, in upper case. */
    public Map<String, KeywordCategory> getKeywords() {
        return Collections.unmodifiableMap(KEYWORDS);
    }

    @Override
    public boolean isName(String word, NamePosition position) {
        KeywordCategory category = KEYWORDS.get(word.toUpperCase(Locale.ROOT));
        if (category == null) {
            return true;
        }
        switch (position) {
            case LABEL:
                return true;
            case BARE_ALIAS:
                return false;
            case FUNCTION:
                // DuckDB's grammar special-cases functions named by column-name keywords
                // (COALESCE, NULLIF, IF, GREATEST, ...), so only reserved keywords are rejected
                return category != KeywordCategory.RESERVED;
            case NAME:
            default:
                return category == KeywordCategory.UNRESERVED
                        || category == KeywordCategory.COLUMN_NAME;
        }
    }
